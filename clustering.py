from sklearn.preprocessing import normalize

df_norm = normalize(df, norm='l2')
df_norm = pd.DataFrame(df_norm, index=df.index, columns=df.columns)
df_norm

km = km.fit(df_norm)
labels_norm = km.predict(df_norm)
size_norm = pd.Series(labels_norm).value_counts().sort_index()
size_norm

#6
from scipy.spatial.distance import cosine


centroids = km.cluster_centers_

for i in range(5):
  mask = (labels_norm == i)
  art = df_norm[mask]
  cos_dist = []
  for j in art.values:
    cos_dist.append(cosine(j, centroids[i]))
  cos_dist = pd.Series(cos_dist, index=art.index)
  art_10 = cos_dist.sort_values().head(10)
  art_10 = list(art_10.index)
  print('Кластер', i, art_10)

