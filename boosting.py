from xgboost.sklearn import XGBRegressor

params = {
    'max_depth' : 6,
    'learning_rate' : 0.1,
    'n_estimators' : 400,
    'gamma' : 0.1,
    'random_state' : 42
}

best_rmse = 10000000000000
best_par = params.copy()
for m_d in [4, 5, 6]:
  for l_r in [0.05, 0.1, 0.15]:
    for n_e in [150, 300]:
      for g in [0, 0.1, 0.3]:
        model = XGBRegressor(max_depth=m_d, learning_rate=l_r, n_estimators=n_e, gamma=g, random_state=69)
        model.fit(X_train, y_train)
        val_pred = model.predict(X_val)
        rmse = mean_squared_error(y_val, val_pred) ** 0.5
        if rmse < best_rmse:
          best_rmse = rmse
          best_params = {'max_depth': m_d, 'learning_rate': l_r, 'n_estimators': n_e, 'gamma': g, 'random_state': 69}
xgb = XGBRegressor(max_depth=best_params['max_depth'], learning_rate=best_params['learning_rate'], n_estimators=best_params['n_estimators'], gamma=best_params['gamma'], random_state=69)

xgb.fit(X_train, y_train)
test_pred = xgb.predict(X_test)

print('MAPE: ', mean_absolute_percentage_error(y_test, test_pred))
print('RMSE: ', mean_squared_error(y_test, test_pred)**0.5)

