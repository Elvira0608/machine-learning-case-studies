from sklearn.model_selection import train_test_split

df = df.drop(columns=['salary', 'salary_currency'])
X = df.drop(columns=['salary_in_usd'])
y = df['salary_in_usd']
X_train_0, X_test, y_train_0, y_test = train_test_split(X, y, test_size=0.1, random_state=69)
X_train, X_val, y_train, y_val = train_test_split(X_train_0, y_train_0, test_size=1/9, random_state=69)

X_train_0 = X_train
X_val_0 = X_val
X_test_0 = X_test

df.dtypes

#2
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_percentage_error, mean_squared_error
from sklearn.preprocessing import OneHotEncoder
import numpy as np

cat_features = ['experience_level', 'employment_type', 'job_title', 'employee_residence', 'company_location', 'company_size']
num_features = ['work_year', 'remote_ratio']
encoder = OneHotEncoder(handle_unknown='ignore', sparse_output=False)

X_train_cat = encoder.fit_transform(X_train[cat_features])
X_val_cat = encoder.transform(X_val[cat_features])
X_test_cat = encoder.transform(X_test[cat_features])

X_train_num = X_train[num_features]
X_val_num = X_val[num_features]
X_test_num = X_test[num_features]

X_train = pd.concat([pd.DataFrame(X_train_cat).reset_index(drop=True), X_train_num.reset_index(drop=True)], axis=1)

X_val = pd.concat([pd.DataFrame(X_val_cat).reset_index(drop=True), X_val_num.reset_index(drop=True)], axis=1)

X_test = pd.concat([pd.DataFrame(X_test_cat).reset_index(drop=True), X_test_num.reset_index(drop=True)], axis=1)

X_train.columns = X_train.columns.astype(str)
X_val.columns = X_val.columns.astype(str)
X_test.columns = X_test.columns.astype(str)

lr = LinearRegression()
lr.fit(X_train, y_train)

val_pred = lr.predict(X_val)

print('MAPE: ', mean_absolute_percentage_error(y_val, val_pred))
print('RMSE: ', mean_squared_error(y_val, val_pred)**0.5)

